"""Generate arc/api/arc_api_table.inc and arc/api/arc_api_classes.inc from the real engine's ObjC
metadata (tools/arccore-1.170.0-objc.tsv, written by tools/dump_objc.m).

The table lists every ObjC-typed method of the 146 Arc classes. At load time, arc_api_stubs.mm adds a
logging stub for each one that our code hasn't implemented. Methods with C++ types in their signature are
left out: Swift can't call them, they are ArcCore's internal plumbing.

  python3 arc/tools/gen_api_table.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
API = os.path.join(os.path.dirname(HERE), "api")
OK_STRUCTS = {"CGSize", "CGPoint", "CGRect"}


def return_kind(enc):
    """Map a method type encoding's return type to a stub kind."""
    enc = enc.lstrip("rnNoORV")
    if enc.startswith("v"):
        return "void"
    if enc.startswith("{CGSize") or enc.startswith("{CGPoint"):
        return "pair"  # two doubles, returned in d0/d1
    if enc.startswith("{CGRect"):
        return "rect"  # 32 bytes, returned indirectly through x8
    if enc.startswith("f"):
        return "float"
    if enc.startswith("d"):
        return "double"
    return "word"  # id, Class, SEL, pointers, integers and BOOL: x0


rows = [l.rstrip("\n").split("\t") for l in open(os.path.join(HERE, "arccore-1.170.0-objc.tsv"))]
# Classes with a hand-written primary @implementation (not a category) are declared there, not in the shell.
hand_written = set()
for d, _, files in os.walk(os.path.dirname(HERE)):
    for name in files:
        if name.endswith(".mm") and name != "arc_api_stubs.mm":
            hand_written |= set(re.findall(r"^@implementation\s+(Arc\w+)\s*$", open(os.path.join(d, name)).read(), re.M))
classes = sorted(r[1] for r in rows if r[0] == "C" and r[1] not in hand_written)
methods = []
for r in rows:
    if r[0] != "M":
        continue
    _, cls, kind, sel, enc = r
    if sel.startswith(".cxx_") or sel == "dealloc":
        continue
    if any(n not in OK_STRUCTS for n in re.findall(r"\{([^=}]*)", enc)):
        continue
    methods.append((cls, kind, sel, enc, return_kind(enc)))

with open(os.path.join(API, "arc_api_classes.inc"), "w") as f:
    f.write("// Generated by arc/tools/gen_api_table.py from ArcCore 1.170.0 metadata. Do not edit.\n")
    for c in classes:
        f.write("ARC_CLASS(%s)\n" % c)

with open(os.path.join(API, "arc_api_table.inc"), "w") as f:
    f.write("// Generated by arc/tools/gen_api_table.py from ArcCore 1.170.0 metadata. Do not edit.\n")
    f.write("// {class, is_class_method, selector, type encoding, return kind}\n")
    for cls, kind, sel, enc, rk in sorted(methods):
        f.write('{"%s", %s, "%s", "%s", ArcStubReturn::k%s},\n' % (cls, "true" if kind == "+" else "false", sel, enc, rk.capitalize()))

print("%d shell classes (%d hand-written), %d ObjC-typed methods" % (len(classes), len(hand_written), len(methods)))
